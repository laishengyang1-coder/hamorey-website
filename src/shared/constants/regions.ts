/**
 * 把历史简称归一到官方全称（用于回填老数据 / 兜底校验）
 */
export function normalizeProvince(input: string | null | undefined): string {
  const v = (input || '').trim();
  if (!v) return '';
  const direct = PROVINCES.find((p) => p === v);
  if (direct) return direct;
  // 简称 → 全称：去掉尾部「省/市/自治区」后按前缀匹配
  const bare = v.replace(/(省|市|自治区|特别行政区|壮族|回族|维吾尔)$/g, '');
  const hit = PROVINCES.find((p) => p.replace(/(省|市|自治区|特别行政区|壮族|回族|维吾尔)$/g, '') === bare);
  return hit || v;
}
